/// <summary>
/// Расшифровка отказа подключения для интерфейса: что произошло, что это значит на самом деле и что
/// сделать по шагам. Служба собирает её из кода ошибки, протокола и того, что видно в сертификате сервера.
/// </summary>
public sealed record ConnectionErrorHelp
{
    /// <summary>Одной строкой, без кода: с этого начинается блок ошибки.</summary>
    public string Summary { get; init; } = "";

    /// <summary>Механика отказа: почему Windows ответила именно так.</summary>
    public string Meaning { get; init; } = "";

    /// <summary>Что делать, от самого вероятного к крайним мерам.</summary>
    public IReadOnlyList<string> Steps { get; init; } = [];

    /// <summary>Код словами: «Код 0x80092013 (−2146885613), CryptoAPI».</summary>
    public string? CodeText { get; init; }

    /// <summary>Сертификат сервера, если его удалось посмотреть пробой.</summary>
    public string? CertificateText { get; init; }
}

