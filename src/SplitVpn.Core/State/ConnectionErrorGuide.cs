    public static ConnectionErrorHelp For(
        ErrorCategory category,
        int? code,
        VpnProtocol protocol,
        AuthMethod authMethod,
        ServerCertificateFacts? certificate,
        DateTimeOffset now)
    {
        var (summary, meaning, steps) = Describe(category, code, protocol, authMethod, certificate, now);
        return new ConnectionErrorHelp
        {
            Summary = summary,
            Meaning = meaning,
            Steps = steps,
            CodeText = code is { } value ? CodeText(value) : null,
            CertificateText = certificate?.Describe(now),
        };
    }

    /// <summary>Код словами: десятичный для RAS, шестнадцатеричный с источником — для системных.</summary>
    public static string CodeText(int code)
    {
        var source = code switch
        {
            >= 600 and <= 950 => "RAS",
            >= 13000 and <= 14000 => "IKE",
            _ when (code & unchecked((int)0xFFFF0000)) == unchecked((int)0x80090000) => "CryptoAPI",
            _ when (code & unchecked((int)0xFFFF0000)) == unchecked((int)0x800B0000) => "проверка сертификата",
            _ => "Windows",
        };

        return code is >= 0 and <= 0xFFFF
            ? string.Create(CultureInfo.InvariantCulture, $"Код {code} ({source})")
            : string.Create(CultureInfo.InvariantCulture, $"Код 0x{(uint)code:X8} ({code}, {source})");
    }

    private static (string Summary, string Meaning, IReadOnlyList<string> Steps) Describe(
        ErrorCategory category, int? code, VpnProtocol protocol, AuthMethod authMethod, ServerCertificateFacts? certificate, DateTimeOffset now)
    {
        if (code is { } value && Known(value, protocol, certificate, now) is { } known)
        {
            return known;
        }

        return ByCategory(category, protocol, authMethod);
    }

