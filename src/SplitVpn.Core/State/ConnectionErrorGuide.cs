    private static string CertificateExpiredMeaning(ServerCertificateFacts? certificate, DateTimeOffset now) =>
        certificate is { } facts && facts.Expired(now)
            ? "Сервер предъявил сертификат, срок действия которого уже закончился. Проверка сертификатов Windows "
                + "такие подключения не пропускает."
            : "Windows считает срок действия сертификата истёкшим. Это бывает и при неверных часах компьютера: "
                + "тогда сертификат исправен, а «истёкшим» его делает время на этой машине.";

    private static string RevocationSuffix(ServerCertificateFacts? certificate) =>
        certificate is { RevocationHosts.Count: > 0 } facts ? " (" + string.Join(", ", facts.RevocationHosts) + ")" : "";

    private static string NamesSuffix(ServerCertificateFacts? certificate) =>
        certificate is { Names.Count: > 0 } facts ? ": " + string.Join(", ", facts.Names.Take(5)) : "";
